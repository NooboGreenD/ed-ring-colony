/** Текст сообщения на языке интерфейса: подставляет значения в шаблон. */
export function issueText(
  issue: { code: string; params?: Record<string, string | number> },
  locale: string,
): string {
  const dict = exchangeTranslations[locale] || exchangeTranslations.ru;
  const template = dict[issue.code] ?? exchangeTranslations.ru[issue.code] ?? issue.code;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(issue.params?.[name] ?? `{${name}}`));
}
