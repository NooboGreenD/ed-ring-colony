/** Перевод одной подписи: в React это `t` из `useI18n()`. */
type MiniTranslate = (key: string) => string;

/** Значения, которыми Helper помечает «своё» открытие вместо имени пилота. */
const SELF_MARKERS = new Set(['Вы', 'You', 'self']);
const OTHER_MARKERS = new Set(['Другой пилот', 'Another pilot', 'other']);

/**
 * Подпись первооткрывателя: имя командира как есть, а служебные метки —
 * на языке интерфейса.
 *
 * Helper пишет в `first_discovered_by` не имя, а пометку «Вы»/«Другой пилот»,
 * когда тело открыл сам командир или пилот без имени в журнале. На сайте эта
 * пометка висела по-русски на всех языках, поэтому переводим её здесь.
 */
export function discoveredByLabel(value: string, t: MiniTranslate): string {
  const text = String(value || '');
  if (SELF_MARKERS.has(text)) return t('orrery.discoveredByYou');
  if (OTHER_MARKERS.has(text)) return t('orrery.discoveredByOther');
  return text;
}
