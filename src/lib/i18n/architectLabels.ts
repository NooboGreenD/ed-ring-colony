/** Перевод подписи справочника; неизвестный идентификатор — русский текст. */
export function architectLabel(
  kind: 'preReq' | 'unlock' | 'economy' | 'buildClass' | 'pad', id: string, fallback: string, t: (key: string) => string): string {
  const key = `arch.${kind}.${id}`;
  const label = t(key);
  return label === key ? fallback : label;
}

